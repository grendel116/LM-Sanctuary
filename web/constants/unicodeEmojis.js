export function applySkinTone(glyph, tone = '') {
  if (!tone || !SKIN_TONE_BASE_SET.has(glyph)) return glyph;
  const clean = glyph.endsWith('\uFE0F') ? glyph.slice(0, -1) : glyph;
  return `${clean}${tone}`;
}

function isoToFlag(code) {
  const upper = String(code || '').trim().toUpperCase();
  if (upper.length !== 2) return '';
  const a = upper.codePointAt(0) - 65 + 0x1F1E6;
  const b = upper.codePointAt(1) - 65 + 0x1F1E6;
  return String.fromCodePoint(a, b);
}

